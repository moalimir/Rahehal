type PublicRouteSpec = {
  code: string;
  path: string;
  title: string;
  eyebrow: string;
  summary: string;
  action: string;
  status: string;
  details: string[];
  steps?: string[];
};

const metrics: Metric[] = [
  { label: "وضعیت", value: "فعال", trend: "نمونه نمایشی" },
  { label: "ردپای اقدام", value: "ثبت‌شده", trend: "نسخه‌دار" },
  { label: "پشتیبانی", value: "RTL", trend: "دسکتاپ و موبایل" },
];

function definePublicRoute(spec: PublicRouteSpec): RouteDefinition {
  const details = [...spec.details];
  while (details.length < 9) details.push("اقدام بعدی و مسئول آن در همان صفحه روشن است");
  return {
    code: spec.code,
    path: spec.path,
    role: "public",
    title: spec.title,
    eyebrow: spec.eyebrow,
    summary: spec.summary,
    primaryAction: spec.action,
    status: spec.status,
    owner: "تیم محصول راه‌حل",
    deadline: "زمان تهران · نمونه نمایشی",
    confidentiality: spec.path.startsWith("/auth") ? "خصوصی" : "عمومی و کنترل‌شده",
    metrics,
    sections: [
      {
        title: "آنچه باید بدانید",
        description: "اطلاعات اصلی این مرحله",
        items: details.slice(0, 3),
      },
      {
        title: "کنترل و اعتماد",
        description: "قواعدی که تصمیم را قابل پیگیری می‌کند",
        items: details.slice(3, 6),
      },
      { title: "اقدام بعدی", description: "مسیر روشن ادامه کار", items: details.slice(6, 9) },
    ],
    steps: spec.steps ?? ["بررسی اطلاعات", "تکمیل پیش‌شرط", "ثبت اقدام", "دریافت رسید"],
    records: details.slice(0, 4).map((item, index) => ({
      موضوع: item,
      وضعیت: index === 2 ? "نیازمند اقدام" : "آماده",
      مسئول: index % 2 === 0 ? "کاربر" : "تیم راه‌حل",
      موعد: index === 2 ? "امروز" : "ثبت‌شده",
    })),
  };
}

