import type { Metric, RoleSpace, RouteDefinition } from "@/types";

interface Spec {
  code: string;
  path: string;
  role: RoleSpace;
  title: string;
  eyebrow: string;
  summary: string;
  action: string;
  status: string;
  owner: string;
  deadline: string;
  confidentiality: string;
  metrics: Metric[];
  focus: string[];
  steps: string[];
}

function define(spec: Spec): RouteDefinition {
  const first = spec.focus.slice(0, 3);
  const second = spec.focus.slice(3, 6);
  const third = spec.focus.slice(6, 9);
  const labels = ["اولویت فوری", "در حال بررسی", "شاهد ثبت‌شده", "اقدام برنامه‌ریزی‌شده"];

  return {
    code: spec.code,
    path: spec.path,
    role: spec.role,
    title: spec.title,
    eyebrow: spec.eyebrow,
    summary: spec.summary,
    primaryAction: spec.action,
    status: spec.status,
    owner: spec.owner,
    deadline: spec.deadline,
    confidentiality: spec.confidentiality,
    metrics: spec.metrics,
    sections: [
      {
        title: "تصویر فعلی پرونده",
        description: "اطلاعاتی که برای تصمیم امروز لازم است، همراه با وضعیت و مسئول روشن.",
        items: first,
      },
      {
        title: "کنترل‌ها و شواهد",
        description: "هر تصمیم حساس به نسخه، دلیل، مدرک و ردپای حسابرسی متصل است.",
        items: second,
      },
      {
        title: "پیش از رفتن به مرحله بعد",
        description: "شرط‌های عبور مرحله و مواردی که هنوز باید تکمیل شوند.",
        items:
          third.length > 0
            ? third
            : ["مالک مرحله تأیید شده است", "SLA و اعلان فعال است", "نسخه جاری قفل و ثبت شده است"],
      },
    ],
    steps: spec.steps,
    records: spec.focus.slice(0, 4).map((item, index) => ({
      موضوع: item,
      وضعیت: labels[index] ?? "ثبت‌شده",
      مسئول: index % 2 === 0 ? spec.owner : "همکار پرونده",
      موعد: index === 0 ? spec.deadline : `۱۴۰۵/۰۵/${String(15 + index).padStart(2, "۰")}`,
    })),
  };
}

